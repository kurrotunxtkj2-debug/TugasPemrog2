    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
try {
Connection conn= Koneksi.getKoneksi();

String sql = "INSERT INTO penjualan(tanggal_penjualan, total) VALUES(?,?)";
PreparedStatement pst= conn.prepareStatement(sql);

pst.setString(1, txtTanggal.getText());
pst.setInt(2, Integer.parseInt(txtSumtotal.getText()));

pst.executeUpdate();
JOptionPane.showMessageDialog(null, "Transaksi berhasil di simpan");
}catch (Exception e){
    JOptionPane.showMessageDialog(null, e.getMessage());
}
// TODO add your handling code here:

    }//GEN-LAST:event_btnSimpanActionPerformed

