    private void cmbMenuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbMenuActionPerformed
          try {
        Connection conn = Koneksi.getKoneksi();

        String sql = "SELECT harga FROM menu WHERE nama_menu=?";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, cmbMenu.getSelectedItem().toString());

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            txtHarga.setText(rs.getString("harga"));
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(null, e.getMessage());
    }

    }//GEN-LAST:event_cmbMenuActionPerformed

    private void txtJumlahKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtJumlahKeyReleased
try {
    int harga = Integer.parseInt(txtHarga.getText());
    int jumlah = Integer.parseInt(txtJumlah.getText());

    int subtotal = harga * jumlah;

    txtSumtotal.setText(String.valueOf(subtotal));

} catch (Exception e) {
    txtSumtotal.setText("");
}        // TODO add your handling code here:
    }//GEN-LAST:event_txtJumlahKeyReleased

